"""Rebuild docs/benchmarks.md from the newest result file per configuration in eval/results/.

Usage:
    python eval/summarize.py
"""

from __future__ import annotations

import json
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
REPO = EVAL_DIR.parent
OUT = REPO / "docs" / "benchmarks.md"


def fmt(metric: dict) -> str:
    if metric["mean"] is None:
        return "n/a"
    failed = f", {metric['failed']} failed" if metric["failed"] else ""
    return f"{metric['mean']:.3f} (n={metric['n']}{failed})"


def main() -> None:
    latest: dict[str, tuple[str, dict]] = {}
    for path in sorted(EVAL_DIR.glob("results/*.json")):
        result = json.loads(path.read_text())
        latest[result["meta"]["configuration"]] = (path.name, result)
    if not latest:
        raise SystemExit("no results in eval/results/")

    lines = [
        "# Benchmarks",
        "",
        "Generated by `python eval/summarize.py` from the newest file per configuration in `eval/results/`.",
        "Do not edit by hand.",
        "",
        "| config | faithfulness | answer relevancy | context precision | refusal accuracy | false refusals | mean revisions | latency p50 / p95 (s) | cost (USD) | errors |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for key in sorted(latest):
        _, r = latest[key]
        s, m = r["summary"], r["meta"]
        ra, fr = s["refusal_accuracy"], s["false_refusals"]
        cost = s["cost_usd"]["pipeline"] + s["cost_usd"]["judge"]
        lat = s["latency_s"] or {"p50": float("nan"), "p95": float("nan")}
        lines.append(
            f"| {key}: {m['configuration_label']} | {fmt(s['faithfulness'])} | {fmt(s['answer_relevancy'])} | "
            f"{fmt(s['context_precision'])} | {ra['correct']}/{ra['n']} | {fr['count']}/{fr['n']} | "
            f"{s['mean_revisions']} | {lat['p50']} / {lat['p95']} | {cost:.2f} | {s['n_errors']} |"
        )

    lines += ["", "## Run details", ""]
    for key in sorted(latest):
        name, r = latest[key]
        m = r["meta"]
        lines += [
            f"**{key}** (`eval/results/{name}`)",
            f"- Command: `{m['command']}`",
            f"- Date: {m['date']}; commit `{m['git_commit'][:10]}`{' (uncommitted changes)' if m['git_dirty'] else ''}",
            f"- Questions: {m['n_questions']} from `{m['questions_file']}` (sha256 `{m['questions_sha256'][:12]}`); "
            f"corpus manifest sha256 `{m['corpus_manifest_sha256'][:12]}`; {m['index_chunks']} indexed chunks",
            f"- Pipeline: {m['pipeline']['model']} at temperature {m['pipeline']['temperature']}, "
            f"embeddings {m['pipeline']['embedding_model']}, k={m['pipeline']['retrieval_k']}",
            f"- Judge: {m['judge']['model']} at temperature {m['judge']['temperature']}, ragas {m['packages']['ragas']}",
            f"- Hardware: {m['hardware']}",
            "",
        ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(REPO)} ({len(latest)} configurations)")


if __name__ == "__main__":
    main()
